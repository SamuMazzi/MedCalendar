import Head from 'next/head'
import { useRouter } from 'next/router'
import { useState } from 'react'
import styles from '../styles/Home.module.css'
import { Grid, Button, Typography } from '@mui/material'
import { MenuAppBar } from '../components/app_bar'
import SelectDistretto from '../components/select_distretto'

export default function Home() {
  const [ distretto, setDistretto ] = useState("");
  const router = useRouter();

  const pushWithDistretto = (path: string) => {
    router.push({
      pathname: path,
      query: { distretto: distretto },
    })
  }

  return (
    <div className={styles.container}>
      <Head>
        <title>Programmazione turni</title>
        <meta name="description" content="Generated by create next app" />
        <link rel="icon" href="/favicon.ico" />
      </Head>
      <MenuAppBar />
      <main className={styles.main}>
        <Grid container spacing={2} 
          direction="column"
          alignItems="center"
          justifyContent="flex-start"
          style={{ minHeight: '100vh' }}
        >
          <Typography variant="h1" component="h1">
            Benvenuto
          </Typography>
          {
            !distretto && 
            <Typography variant="h6" component="h6">
              Per continuare seleziona un distretto
            </Typography>
          }
          {
            <Grid item>
              <SelectDistretto distretto={distretto} setDistretto={setDistretto}/>
            </Grid>
          }
          {
            distretto && 
              <Grid item xs={6} md={6}>
                <Button onClick={() => pushWithDistretto('/raccolta_disponibilita')}>Raccolta disponibilità</Button>
              </Grid>
          }
          {
            distretto &&
            <Grid item xs={6} md={6}>
              <Button onClick={() => pushWithDistretto('/cambio_turno')}>Cambio turno</Button>
            </Grid>
          }
          {
            distretto && true && //authState.admin && distrettiAdmin.indexOf(distretto) >= 0
              <Grid item xs={6} md={6}>
                <Button onClick={() => pushWithDistretto('/admin_page')}>Sezione amministratore</Button>
              </Grid>
          }
        </Grid>
      </main>
    </div>
  )
}
